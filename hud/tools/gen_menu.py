#!/usr/bin/env python3
"""
Writes hud/panorama/layout/custom_game/arenas_menu.xml - the !guns / !rounds menu.

The layout is mostly pools (96 weapon tiles, 16 round tiles), so it is generated rather than typed. The pool sizes
here are the same numbers as src-plugin/Plugin/PreferencesMenu.cs; change both or rows silently go missing.

    python3 -I hud/tools/gen_menu.py
"""
from pathlib import Path

GROUPS = 6          # weapon categories: rifle, sniper, smg, lmg, shotgun, pistol
TILES = 16          # per category: Random + up to 15 weapons
PER_LINE = 8        # Panorama does not wrap, so each line of 8 is its own panel
ROUNDS = 16         # round type tiles
ROUNDS_PER_LINE = 4

OUT = Path(__file__).resolve().parents[1] / "panorama/layout/custom_game/arenas_menu.xml"

HEADER = """<root>
	<styles>
		<include src="s2r://panorama/styles/custom_game/hud_shared.vcss_c" />
		<include src="s2r://panorama/styles/custom_game/arenas_menu.vcss_c" />
	</styles>

	<!--
		!guns and !rounds - the Arena 1v1 preferences menu. Generated by hud/tools/gen_menu.py, driven by
		src-plugin/Plugin/PreferencesMenu.cs. Replaces the KitsuneMenu center menus: one card, two tabs.

		CONTRACT (PreferencesMenu.cs must match)
		  RootPanelId = "ArenasMenuRoot"   RevealClass = "show"   CloseButtonId = "am_close"   RowCount = 0
		  CaptureInput = true              HideHud = None         SharedText = false

		POOLS
		  am_g0..am_g5               weapon categories, in the order the plugin fills them
		  am_gN_w0..am_gN_w15        tiles, 8 per line (am_gN_l0, am_gN_l1); w0 is Random
		  am_r0..am_r15              round types, 4 per line (am_rl0..am_rl3)

		BUTTONS (PanelAction.Button, by id)
		  am_close am_done           close (am_close is the library's)
		  am_tab0 am_tab1            weapons, rounds
		  am_gN_wM                   pick weapon M of category N (w0 = random)
		  am_rN                      turn round type N on or off

		DIALOG VARIABLES
		  am_title am_tag am_tab0 am_tab1 am_hint am_done am_r_intro
		  am_gN_k am_gN_v            category name, current pick
		  am_gN_wM                   tile caption
		  am_rN am_rN_s am_rN_c      round name, ON / OFF, chip (HS)

		CLASSES THE SERVER TOGGLES
		  am_tab0 am_tab1, am_pg0 am_pg1   active
		  am_bar                     at-0 | at-1
		  am_gN, am_gN_l1, am_gN_wM  hidden
		  am_gN_wM                   sel | one i-<weapon> (i-ak47, i-awp, ... i-random)
		  am_rl0..am_rl3, am_rN      hidden
		  am_rN                      on, has-chip | one i-<weapon> or i-none
		  am_hint                    warn
	-->
	<Panel class="hud-screen" hittest="false">
		<Panel id="ArenasMenuRoot" class="hud-root hud-card am-root">
			<Panel class="hud-head">
				<Label class="hud-title am-title" text="{s:am_title}" />
				<Label class="hud-tag am-tag" text="{s:am_tag}" />
				<Panel class="am-fill" hittest="false" />
				<Button id="am_close" class="hud-exit"><Label class="hud-x" text="&#x2715;" /></Button>
			</Panel>
			<Panel class="am-tabs">
				<Button id="am_tab0" class="am-tab"><Label class="am-tab-lbl" text="{s:am_tab0}" /></Button>
				<Button id="am_tab1" class="am-tab"><Label class="am-tab-lbl" text="{s:am_tab1}" /></Button>
				<Panel id="am_bar" class="am-bar" hittest="false" />
			</Panel>
			<Panel class="am-body" hittest="false">
"""

FOOTER = """			</Panel>
			<Panel class="hud-foot">
				<Label id="am_hint" class="hud-hint am-hint" text="{s:am_hint}" />
				<Button id="am_done" class="hud-btn"><Label class="hud-btn-lbl" text="{s:am_done}" /></Button>
			</Panel>
		</Panel>
	</Panel>
</root>
"""


def weapon_page() -> str:
    out = ['\t\t\t\t<Panel id="am_pg0" class="am-page" hittest="false">']
    for g in range(GROUPS):
        out.append(f'\t\t\t\t\t<Panel id="am_g{g}" class="am-grp hidden" hittest="false">')
        out.append('\t\t\t\t\t\t<Panel class="am-grp-k" hittest="false">')
        out.append(f'\t\t\t\t\t\t\t<Label class="am-grp-name" text="{{s:am_g{g}_k}}" />')
        out.append(f'\t\t\t\t\t\t\t<Label class="am-grp-cur" text="{{s:am_g{g}_v}}" />')
        out.append('\t\t\t\t\t\t</Panel>')
        out.append('\t\t\t\t\t\t<Panel class="am-grp-tiles" hittest="false">')
        for line in range(TILES // PER_LINE):
            hidden = " hidden" if line > 0 else ""
            out.append(f'\t\t\t\t\t\t\t<Panel id="am_g{g}_l{line}" class="am-line{hidden}" hittest="false">')
            for t in range(line * PER_LINE, (line + 1) * PER_LINE):
                tid = f"am_g{g}_w{t}"
                out.append(
                    f'\t\t\t\t\t\t\t\t<Button id="{tid}" class="am-wt hidden">'
                    f'<Panel class="am-img" hittest="false" />'
                    f'<Label class="am-wt-lbl" text="{{s:{tid}}}" /></Button>'
                )
            out.append('\t\t\t\t\t\t\t</Panel>')
        out.append('\t\t\t\t\t\t</Panel>')
        out.append('\t\t\t\t\t</Panel>')
    out.append('\t\t\t\t</Panel>')
    return "\n".join(out) + "\n"


def round_page() -> str:
    out = ['\t\t\t\t<Panel id="am_pg1" class="am-page" hittest="false">']
    out.append('\t\t\t\t\t<Label class="am-intro" text="{s:am_r_intro}" />')
    for line in range(ROUNDS // ROUNDS_PER_LINE):
        out.append(f'\t\t\t\t\t<Panel id="am_rl{line}" class="am-rline hidden" hittest="false">')
        for r in range(line * ROUNDS_PER_LINE, (line + 1) * ROUNDS_PER_LINE):
            rid = f"am_r{r}"
            out.append(
                f'\t\t\t\t\t\t<Button id="{rid}" class="am-rt hidden">'
                f'<Panel class="am-rt-icon" hittest="false"><Panel class="am-img" hittest="false" /></Panel>'
                f'<Panel class="am-rt-text" hittest="false">'
                f'<Panel class="am-rt-top" hittest="false">'
                f'<Label class="am-rt-name" text="{{s:{rid}}}" />'
                f'<Label class="am-rt-chip" text="{{s:{rid}_c}}" />'
                f'</Panel>'
                f'<Label class="am-rt-state" text="{{s:{rid}_s}}" />'
                f'</Panel>'
                f'<Panel class="am-rt-check" hittest="false" />'
                f'</Button>'
            )
        out.append('\t\t\t\t\t</Panel>')
    out.append('\t\t\t\t</Panel>')
    return "\n".join(out) + "\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + weapon_page() + "\n" + round_page() + FOOTER)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
